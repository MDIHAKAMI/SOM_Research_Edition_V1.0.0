import type { SheetData } from './workbook';
import { type LiveSession, type Entry, activeEntries, riyadh } from './live';
import { type Trace } from './pharmacology';
import { multimodal, contextAt } from './multimodal';
import { ANCHORS, PD_VERSION } from './pd-registry';
import { HN_SOURCES, REFERENCE_CURVE, HN_MODEL_ASSUMPTIONS, DEFAULT_TAIL_POLICY } from './hn-coefficients';
import { HN_EFFECT_SITES } from './hn-effect-sites';
import { publishedPairs } from './pair-registry';
export function hnSheets(
  session: LiveSession,
  entries: Entry[],
  traces: Trace[],
): SheetData[] {
  const events = activeEntries(entries).filter((e) => e.kind === 'clinical');
  return [
    {
      name: 'HN event states',
      rows: [
        [
          'Entry ID',
          'Seconds',
          'Observed UTC',
          'Observed KSA',
          'Event',
          'H units',
          'N units',
          'H complete',
          'N complete',
          'H excluded',
          'N excluded',
          'Context JSON',
          'Registry version',
          'Snapshot origin',
          'Tail policy',
          'Pooled opioid coordinate',
          'Flags',
          'H known subtotal',
          'N known subtotal',
          'H deliberate omissions',
          'N deliberate omissions',
          'Recorded revision',
          'Snapshot timeline revision',
          'Snapshot trace seconds',
          'Calculated UTC',
          'Retrospective',
          'Selected models JSON',
          'Input entry IDs JSON',
          'Recorded model provenance JSON',
          'Synthetic data',
        ],
        ...events.map((e) => {
          const s = e.snapshot?.multimodal;
          return [
            e.id,
            e.t,
            e.observedAt,
            riyadh(e.observedAt),
            e.data.name,
            s?.H.value,
            s?.N.value,
            s?.H.complete,
            s?.N.complete,
            s?.H.excluded.join('; '),
            s?.N.excluded.join('; '),
            s ? JSON.stringify(s.context) : null,
            s?.version,
            s
              ? 'Original immutable event snapshot'
              : 'Legacy event; H/N was not recorded',
            s?.tailPolicy,
            s?.opioidPool,
            s?.flags?.join('; '),
            s?.H.knownSubtotal,
            s?.N.knownSubtotal,
            s?.H.omitted?.join('; '),
            s?.N.omitted?.join('; '),
            e.recordedRevision,
            e.snapshot?.timelineRevision,
            e.snapshot?.traceAtSeconds,
            e.snapshot?.calculatedAt,
            e.snapshot?.retrospective,
            e.snapshot?.selectedModels ? JSON.stringify(e.snapshot.selectedModels) : null,
            e.snapshot?.inputEntryIds ? JSON.stringify(e.snapshot.inputEntryIds) : null,
            e.snapshot?.modelProvenance ? JSON.stringify(e.snapshot.modelProvenance) : null,
            session.synthetic ?? null,
          ];
        }),
      ],
    },
    {
      name: 'HN event contributions',
      rows: [
        [
          'Entry ID',
          'Seconds',
          'Drug',
          'Domain',
          'Active',
          'Contribution units',
          'Status',
          'Reason',
          'Exposure',
          'Exposure type',
          'Reference parameter',
          'Units',
          'Anchor ID',
          'Anchor type',
          'Endpoint',
          'Source grade',
          'Formula',
          'Source IDs',
          'Flags',
          'Exposure binding',
          'Opioid coordinate',
          'Legacy rho JSON',
          'Population',
          'Context',
          'Background drugs',
          'Age adjustment',
          'Weight adjustment',
          'PMID',
          'DOI',
          'Source',
          'Limits',
          'Version',
        ],
        ...events.flatMap((e) =>
          (e.snapshot?.multimodal?.contributions ?? []).map((c) => [
            e.id,
            e.t,
            c.drug,
            c.domain,
            c.active,
            c.value,
            c.status,
            c.reason,
            c.exposure,
            c.anchor?.exposureType,
            c.anchor?.value,
            c.anchor?.units,
            c.anchor?.id,
            c.anchor?.anchorType,
            c.anchor?.endpoint,
            c.anchor?.evidenceGrade,
            c.formula,
            c.sourceIds?.join('; '),
            c.flags?.join('; '),
            c.exposureBasis,
            c.opioidCoordinate,
            c.rho ? JSON.stringify(c.rho) : null,
            c.anchor?.population,
            c.anchor?.clinicalContext,
            c.anchor?.backgroundDrugs,
            c.anchor?.ageAdjustment,
            c.anchor?.weightAdjustment,
            c.anchor?.pmid,
            c.anchor?.doi,
            c.anchor?.source,
            c.anchor?.limitations,
            c.anchor?.version,
          ]),
        ),
      ],
    },
    {
      name: 'HN reconstructed series',
      rows: [
        [
          'Seconds',
          'UTC',
          'H units',
          'N units',
          'H complete',
          'N complete',
          'H excluded',
          'N excluded',
          'Recorded stimulus category',
          'N2O percent',
          'Spinal bupivacaine',
          'Observed BIS',
          'Dex MOAAS Ce ng-mL',
          ...HN_EFFECT_SITES.map(link => `${link.key} Ce ng-mL`),
          'Tail policy',
          'Pooled opioid coordinate',
          'Flags',
          'H known subtotal',
          'N known subtotal',
          'H deliberate omissions',
          'N deliberate omissions',
          'Version',
          'Origin',
        ],
        ...traces.map((t) => {
          const s = multimodal(
            t,
            session.choice,
            session.patient.age,
            contextAt(entries, t.t),
          );
          return [
            t.t,
            new Date(Date.parse(session.startedAt) + t.t * 1000).toISOString(),
            s.H.value,
            s.N.value,
            s.H.complete,
            s.N.complete,
            s.H.excluded.join('; '),
            s.N.excluded.join('; '),
            s.context.nProfile,
            s.context.n2oPercent,
            s.context.spinalBupivacaine,
            s.context.bis,
            t.endpointCe?.dexmedetomidineMoaas,
            ...HN_EFFECT_SITES.map(link => t.endpointCe?.[link.key]),
            s.tailPolicy,
            s.opioidPool,
            s.flags.join('; '),
            s.H.knownSubtotal,
            s.N.knownSubtotal,
            s.H.omitted.join('; '),
            s.N.omitted.join('; '),
            s.version,
            'Reconstructed from final corrected timeline',
          ];
        }),
      ],
    },
    {
      name: 'Pair event predictions',
      rows: [
        [
          'Entry ID',
          'Seconds',
          'Model ID',
          'Endpoint',
          'Probability 0-1',
          'Excluded active drugs',
          'Excluded background interventions',
          'Reason unavailable',
          'Interpretation',
          'Evidence grade',
          'Exposure basis',
          'Input JSON',
          'Parameters JSON',
          'Source',
          'Limits',
          'Version',
        ],
        ...events.flatMap((e) =>
          (e.snapshot?.interactions ?? []).map((p) => [
            e.id,
            e.t,
            p.modelId,
            p.endpoint,
            p.probability,
            p.excluded.join('; '),
            p.contextExcluded?.join('; '),
            p.reason,
            p.interpretation,
            p.evidenceGrade,
            p.exposure,
            JSON.stringify(p.input),
            JSON.stringify(p.parameters),
            p.source,
            p.limitations,
            p.version,
          ]),
        ),
      ],
    },
    {
      name: 'Pair reconstructed series',
      rows: [
        [
          'Seconds',
          'Model ID',
          'Endpoint',
          'Probability 0-1',
          'Excluded active drugs',
          'Excluded background interventions',
          'Reason unavailable',
          'Version',
          'Origin',
        ],
        ...traces.flatMap((t) =>
          publishedPairs(
            t,
            session.choice,
            session.patient.age,
            contextAt(entries, t.t),
          ).map((p) => [
            t.t,
            p.modelId,
            p.endpoint,
            p.probability,
            p.excluded.join('; '),
            p.contextExcluded.join('; '),
            p.reason,
            p.version,
            'Reconstructed, not original observation',
          ]),
        ),
      ],
    },
    {
      name: 'HN coefficient registry',
      rows: [
        [
          'ID',
          'Drug',
          'Domain',
          'Endpoint',
          'Recorded stimulus category',
          'Exposure type',
          'A',
          'Units',
          'Anchor type',
          'Grade',
          'Enabled',
          'Requirements',
          'Population',
          'Context',
          'Background',
          'Age adjustment',
          'Weight adjustment',
          'PMID',
          'DOI',
          'Citation',
          'Source',
          'Limitations',
          'Overrides',
          'Version',
          'Formula',
          'Source IDs',
          'Derivation',
          'Assumptions JSON',
          'Knots JSON',
          'Parameters JSON',
          'Exposure binding',
        ],
        ...ANCHORS.map((a) => [
          a.id,
          a.drug,
          a.domain,
          a.endpoint,
          a.profile,
          a.exposureType,
          a.value,
          a.units,
          a.anchorType,
          a.evidenceGrade,
          a.enabled,
          a.requirements.join('; '),
          a.population,
          a.clinicalContext,
          a.backgroundDrugs,
          a.ageAdjustment,
          a.weightAdjustment,
          a.pmid,
          a.doi,
          a.citation,
          a.source,
          a.limitations,
          a.interactionOverrides.join('; '),
          a.version,
          a.formula,
          a.sourceIds?.join('; '),
          a.derivation,
          JSON.stringify(a.assumptions),
          JSON.stringify(a.knots),
          JSON.stringify(a.parameters),
          a.binding,
        ]),
      ],
    },
    {
      name: 'HN equations and assumptions',
      rows: [
        ['Field', 'Value'],
        ['Version', PD_VERSION],
        ['H equation', 'H = sum of drug-specific hypnosis credits; each drug retains its own exposure binding and concentration-response function.'],
        ['N equation', 'N = [S_F(pooled opioid coordinate) + S_F(ketamine coordinate) + propofol term + dexmedetomidine term + sevoflurane MAC + desflurane MAC] / 0.59.'],
        ['Opioid allocation', 'The pooled opioid N term is allocated to individual opioids in proportion to their weighted concentrations. Allocation is bookkeeping, not an independently measured interaction.'],
        ['Reference curve', JSON.stringify(REFERENCE_CURVE)],
        ['Default tail policy', DEFAULT_TAIL_POLICY],
        ['Assumptions', JSON.stringify(HN_MODEL_ASSUMPTIONS)],
        ['Context handling', 'Recorded stimulus profile, N2O, spinal block and BIS remain metadata. They do not gate or modify H/N. Published pair equations retain their own applicability rules.'],
        ['Historical records', 'Event snapshots retain their recorded model version and numbers. Reconstructed series use the current version; the two are not interchangeable.'],
        ['Interpretation', 'Exploratory literature-informed indices. No established adequacy, apnea or extubation thresholds.'],
      ],
    },
    {
      name: 'HN sources',
      rows: [
        ['Source ID', 'Study', 'PMID', 'DOI', 'URL', 'Endpoint', 'Population'],
        ...Object.values(HN_SOURCES).map(source => [source.id, source.study, source.pmid, source.doi, source.url, source.endpoint, source.population]),
      ],
    },
    {
      name: 'HN endpoint effect sites',
      rows: [
        ['Key', 'Drug', 'Domain', 'ke0 per min', 'Half-time min', 'Endpoint', 'Source', 'Model combination'],
        ...HN_EFFECT_SITES.map(link => [link.key, link.drug, link.domain, link.ke0, link.halfTimeMinutes, link.endpoint, link.source, link.linkage]),
      ],
    },
    {
      name: 'PD context history',
      rows: [
        [
          'Entry ID',
          'Seconds',
          'Observed UTC',
          'Recorded stimulus category',
          'N2O percent',
          'Spinal bupivacaine',
          'Observed BIS',
          'Active',
          'Author',
        ],
        ...entries
          .filter((e) => e.kind === 'context')
          .map((e) => [
            e.id,
            e.t,
            e.observedAt,
            e.data.nProfile,
            e.data.n2oPercent,
            e.data.spinalBupivacaine,
            e.data.bis,
            activeEntries(entries).some((a) => a.id === e.id),
            e.author,
          ]),
      ],
    },
  ];
}
